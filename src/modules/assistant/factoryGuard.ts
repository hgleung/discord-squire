import type { Vault } from '../../vault.js';
import { noteFields } from './taskNotes.js';

export const FACTORY_FOLDER = 'Factory';
export const PROMPTS_FOLDER = `${FACTORY_FOLDER}/Prompts`;
/** One settings note per job: Factory/Jobs/<job>.md. */
export const JOBS_FOLDER = `${FACTORY_FOLDER}/Jobs`;
/** Folders only code writes: read-only snapshots and health reports. */
export const GENERATED_FOLDERS = ['Squire/Sync', 'Squire/Health'];
export const FACTORY_README = `${FACTORY_FOLDER}/README.md`;

/** The pointer to the process note, for the assistant's and the workers' prompts. */
export const FACTORY_POINTER = `
- ${FACTORY_README} is the owner's description of how factories work (jobs, prompts, evals, shadow, promotion). When asked to build, run, review or improve a factory, read_note it first and follow it. ${FACTORY_FOLDER}/ is theirs: you may read anything in it, but write only eval results and prompt notes with status: testing.`;

/**
 * Factory/ is the owner's: Squire reads all of it, but its tools write only
 * eval results (Factory/Evals/<job>/results/) and prompt notes that are and
 * stay status: testing. Production prompts, the README, job notes and eval
 * cases change only when the owner's own message asks for that note by name,
 * and never from a background task. Throws, saying why, when refused.
 */
export function factoryGuard(
  vault: Vault,
  rel: string,
  action: 'write' | 'move' | 'delete',
  o: { next?: string; ownerText?: string } = {},
): void {
  // Generated folders: the syncs and the vault-health job own them; the notes tools only read,
  // or move a note out when the owner's message names it.
  for (const owned of GENERATED_FOLDERS) {
    const named = !!o.ownerText && o.ownerText.toLowerCase().includes(rel.split('/').at(-1)!.replace(/\.md$/i, '').toLowerCase());
    if ((rel === owned || rel.startsWith(`${owned}/`)) && !(action === 'move' && named)) throw new Error(`${rel} is generated by Squire's ${owned.split('/').at(-1)} job and is read-only to the notes tools.`);
  }
  if (rel !== FACTORY_FOLDER && !rel.startsWith(`${FACTORY_FOLDER}/`)) return;
  const name = rel.split('/').at(-1)!.replace(/\.md$/i, '').toLowerCase();
  const asked = !!o.ownerText && name.length > 2 && o.ownerText.toLowerCase().includes(name);
  if (/^Factory\/Evals\/[^/]+\/results\/[^/]+\.md$/.test(rel) && action === 'write') return;
  if (rel.startsWith(`${PROMPTS_FOLDER}/`) && action === 'write') {
    const now = String(noteFields(vault.read(rel) ?? '').status ?? 'testing').toLowerCase();
    const next = String(noteFields(o.next ?? '').status ?? '').toLowerCase();
    if (now === 'testing' && next === 'testing') return;
    if (asked) return;
    throw new Error(
      now === 'testing'
        ? `${rel} would become status: ${next || '(none)'}; only the owner moves a prompt out of testing.`
        : `${rel} is a ${now} prompt; only the owner changes it. Propose the change as a new prompt note with status: testing instead.`,
    );
  }
  if (asked) return;
  throw new Error(
    `${rel} is in ${FACTORY_FOLDER}/, which the owner controls: you can read it, but ${action === 'write' ? 'edit' : action} it only when their message asks for this note by name. ` +
      'Eval results and testing prompt notes are the only things you write there.',
  );
}

/** Throws when a factory job may not write there (its write_paths). Here, not in governance.ts, so the notes tools can import it without a cycle. */
export function checkWritePath(writePaths: string[] | undefined, job: string | undefined, rel: string) {
  if (!writePaths?.length) return;
  if (writePaths.some((f) => rel === f || rel.startsWith(`${f.replace(/\/+$/, '')}/`))) return;
  throw new Error(`The ${job ?? 'job'} job may write only in ${writePaths.join(', ')}; ${rel} is outside that. Report it instead of saving it, or ask the owner to add the folder to the job's write_paths.`);
}

