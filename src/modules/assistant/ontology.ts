import { BOT_FOLDER, TASKS_FOLDER, TRAINING_FOLDER, WORKOUTS_FOLDER, type Vault } from '../../vault.js';
import { FACTORY_FOLDER } from './factoryGuard.js';
import { noteFields, setNoteFields, wikiLink } from './taskNotes.js';
import { toLocalIso } from './time.js';

/**
 * The vault's core note types, as frontmatter that Obsidian Bases and
 * Dataview can query: lowercase keys, ISO dates, links as quoted "[[...]]".
 * A note says what it is with `type:`. Nothing here is required of the
 * owner's notes: the schemas are what Squire writes, and what the migration
 * adds where a folder already says what a note is.
 *
 * The migration only adds: a missing `type` (or `trip`) field, an index note
 * a folder doesn't have yet, or a move of a typed note into its type's home
 * folder (with a redirect note at the old path when another note links to
 * that path). It never changes a field that is set, never rewrites a body,
 * and never deletes. It is a dry run unless apply is set.
 */

export type NoteType = 'project' | 'trip' | 'person' | 'task' | 'note' | 'place' | 'meeting';

export interface Schema {
  type: NoteType;
  /** Where notes of this type live. Undefined: anywhere. */
  home?: string;
  fields: Record<string, string>;
}

export const SCHEMAS: Schema[] = [
  { type: 'project', home: 'proj-ideas', fields: { status: 'idea | active | paused | done', started: 'date', related: 'list of [[links]]' } },
  { type: 'trip', home: 'Travel', fields: { start: 'date', end: 'date', status: 'planning | booked | done', places: 'list of [[links]]', people: 'list of [[links]]' } },
  { type: 'person', home: 'People', fields: { aliases: 'list', relation: 'text', met: 'date' } },
  { type: 'task', home: TASKS_FOLDER, fields: { status: 'todo | doing | done | failed', output: '[[link]]', requested: 'date', finished: 'date', channel: 'text', job: 'text' } },
  { type: 'note', fields: { tags: 'list', related: 'list of [[links]]', 'source-task': '[[link]]' } },
  { type: 'place', home: 'Places', fields: { category: 'cafe | restaurant | shop | sight | …', city: 'text', address: 'text', maps: 'url', visited: 'date', rating: '1–5', trip: '[[link]]' } },
  { type: 'meeting', home: 'Meetings', fields: { date: 'date', people: 'list of [[links]]', project: '[[link]]' } },
];

/** Folders whose notes already say their type. The second value is any extra field the folder implies. */
const FOLDER_TYPES: { folder: string; type: NoteType; extra?: Record<string, string> }[] = [
  { folder: 'Cafes', type: 'place', extra: { category: 'cafe' } },
  { folder: 'Places', type: 'place' },
  { folder: 'People', type: 'person' },
  { folder: 'Meetings', type: 'meeting' },
  { folder: 'proj-ideas', type: 'project' },
  { folder: TASKS_FOLDER, type: 'task' },
];

/** Folders that get an index note at every level ("fractal"): a hub for each trip and each one-off project folder. */
const INDEXED_ROOTS = ['Travel', 'proj-ideas'];

/** Never touched: the training log's data, the owner's Factory, the bot's own working folders. Recipes have their own factory. */
const LEFT_ALONE = [TRAINING_FOLDER, WORKOUTS_FOLDER, FACTORY_FOLDER, `${BOT_FOLDER}/Inbox`, `${BOT_FOLDER}/Sync`, `${BOT_FOLDER}/Health`, 'Recipes'];

export const ONTOLOGY_NOTE = `${BOT_FOLDER}/Ontology.md`;
const INDEX_START = '<!-- squire:index -->';
const INDEX_END = '<!-- /squire:index -->';

export type Change =
  | { kind: 'fields'; path: string; fields: Record<string, string> }
  | { kind: 'create'; path: string; content: string; why: string }
  | { kind: 'index'; path: string; content: string }
  | { kind: 'move'; from: string; to: string; redirect: boolean };

const under = (path: string, folder: string) => path === folder || path.startsWith(`${folder}/`);
const leftAlone = (path: string) => LEFT_ALONE.some((f) => under(path, f));
const baseName = (path: string) => path.split('/').at(-1)!.replace(/\.md$/, '');
const parentOf = (path: string) => path.split('/').slice(0, -1).join('/');

/** The schemas as a note, for the owner and for Squire to read. */
export function ontologyNote(): string {
  const rows = SCHEMAS.map((s) => `| ${s.type} | ${s.home ?? 'anywhere'} | ${Object.entries(s.fields).map(([k, v]) => `\`${k}\` (${v})`).join(', ')} |`);
  return `---\ntype: note\ntags: [squire-ontology]\n---\n\n# Note types\n\nEvery note can say what it is with \`type:\`. These are the fields Squire writes for each type, so Bases and Dataview can query them. Dates are YYYY-MM-DD, links are quoted "[[Note]]". Generated by Squire; edit the schemas in the code, not here.\n\n| Type | Lives in | Fields |\n|---|---|---|\n${rows.join('\n')}\n\nEach trip folder and project folder has an index note named after the folder, with a generated table of what is in it between \`${INDEX_START}\` markers. Anything outside the markers is yours.\n`;
}

/** The kind of draft a file name says it is: "v2", "draft", or nothing. */
function versionOf(name: string): string {
  const v = /\bv(\d+)\b/i.exec(name);
  if (v) return `v${v[1]}`;
  if (/\bdraft\b/i.test(name)) return 'draft';
  if (/\bfinal\b/i.test(name)) return 'final';
  return '';
}

/** The generated table for a folder's index note: its subfolders' index notes, then its notes, with their version or draft. */
function indexTable(vault: Vault, folder: string, timeZone: string): string {
  const own = `${folder}/${baseName(folder)}.md`;
  const subs = vault.folders(folder).filter((f) => parentOf(f) === folder);
  const notes = vault.list(folder).filter((p) => parentOf(p) === folder && p !== own);
  const rows = [
    ...subs.map((s) => `| ${wikiLink(`${s}/${baseName(s)}`)} | folder | |`),
    ...notes.map((p) => `| ${wikiLink(p)} | ${versionOf(baseName(p)) || '—'} | ${toLocalIso(new Date(vault.mtime(p)), timeZone).slice(0, 10)} |`),
  ];
  return `${INDEX_START}\n| Note | Version | Modified |\n|---|---|---|\n${rows.join('\n')}\n${INDEX_END}`;
}

/** Whether any note links to this path by its folder path (a link by name alone still finds the note after a move). */
function linkedByPath(vault: Vault, path: string, all: string[]): boolean {
  const target = path.replace(/\.md$/, '');
  if (!target.includes('/')) return false;
  const pattern = new RegExp(`\\[\\[${target.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?:[\\]|#])|\\]\\(${encodeURI(target).replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(?:\\.md)?\\)`, 'i');
  return all.some((p) => p !== path && pattern.test(vault.read(p) ?? ''));
}

/** Every change the migration would make, in order. Reads only. */
export function planMigration(vault: Vault, timeZone: string): Change[] {
  const changes: Change[] = [];
  const all = vault.list();
  if (vault.read(ONTOLOGY_NOTE) !== ontologyNote()) changes.push({ kind: 'create', path: ONTOLOGY_NOTE, content: ontologyNote(), why: 'the schemas' });
  const moved = new Set<string>();

  for (const path of all) {
    if (under(path, TRAINING_FOLDER) || under(path, WORKOUTS_FOLDER) || under(path, FACTORY_FOLDER)) continue;
    const fields = noteFields(vault.read(path) ?? '');
    const type = typeof fields.type === 'string' ? (fields.type as NoteType) : undefined;
    // A typed note outside its type's home moves there, from the loose places only: the bot's inbox and notes/.
    const schema = SCHEMAS.find((s) => s.type === type);
    const loose = under(path, `${BOT_FOLDER}/Inbox`) || under(path, 'notes');
    if (schema?.home && loose && type !== 'trip' && type !== 'task' && !under(path, schema.home)) {
      const to = `${schema.home}/${path.split('/').at(-1)}`;
      if (vault.read(to) === undefined) {
        changes.push({ kind: 'move', from: path, to, redirect: linkedByPath(vault, path, all) });
        moved.add(path);
      }
      continue;
    }
    if (leftAlone(path)) continue;
    const add: Record<string, string> = {};
    const byFolder = FOLDER_TYPES.find((f) => under(path, f.folder));
    if (byFolder && !type) {
      add.type = byFolder.type;
      for (const [k, v] of Object.entries(byFolder.extra ?? {})) if (fields[k] === undefined) add[k] = v;
    }
    // Inside a trip folder: the hub is the trip, every other note links to it.
    const trip = /^Travel\/([^/]+)\//.exec(path)?.[1];
    if (trip) {
      const hub = `Travel/${trip}/${trip}.md`;
      if (path === hub) {
        if (!type) add.type = 'trip';
      } else if (fields.trip === undefined) add.trip = wikiLink(hub);
    }
    if (Object.keys(add).length) changes.push({ kind: 'fields', path, fields: add });
  }

  // Index notes: every folder under the indexed roots gets one named after it.
  for (const root of INDEXED_ROOTS) {
    if (!vault.isDir(root)) continue;
    for (const folder of [root, ...vault.folders(root)]) {
      const path = `${folder}/${baseName(folder)}.md`;
      const table = indexTable(vault, folder, timeZone);
      const existing = vault.read(path);
      if (existing === undefined) {
        const type = folder === root ? 'note' : root === 'Travel' && parentOf(folder) === 'Travel' ? 'trip' : root === 'proj-ideas' ? 'project' : 'note';
        changes.push({ kind: 'create', path, content: `---\ntype: ${type}\ntags: [squire-index]\n---\n\n# ${baseName(folder)}\n\n${table}\n`, why: 'index note' });
      } else if (existing.includes(INDEX_START) && existing.includes(INDEX_END)) {
        const next = existing.replace(new RegExp(`${INDEX_START}[\\s\\S]*?${INDEX_END}`), table);
        if (next !== existing) changes.push({ kind: 'index', path, content: next });
      }
    }
  }
  return changes;
}

/** One line per change, for the dry run and the migration log. */
export function describe(c: Change): string {
  if (c.kind === 'fields') return `add fields  ${c.path}: ${Object.entries(c.fields).map(([k, v]) => `${k}: ${v}`).join(', ')}`;
  if (c.kind === 'create') return `create      ${c.path} (${c.why})`;
  if (c.kind === 'index') return `index table ${c.path}`;
  return `move        ${c.from} -> ${c.to}${c.redirect ? ' (redirect note left at the old path: something links to it by path)' : ''}`;
}

/**
 * Applies a plan made by planMigration. Each change re-checks the vault first:
 * a field the owner has since set, or a note that now exists, is skipped.
 * Writes the log to Squire/Migrations/<date>.md. Returns what it did.
 */
export function applyMigration(vault: Vault, changes: Change[], timeZone: string, now = new Date()): { done: string[]; skipped: string[]; log: string } {
  const done: string[] = [];
  const skipped: string[] = [];
  for (const c of changes) {
    try {
      if (c.kind === 'fields') {
        const text = vault.read(c.path);
        if (text === undefined) throw new Error('gone');
        const current = noteFields(text);
        const add = Object.fromEntries(Object.entries(c.fields).filter(([k]) => current[k] === undefined));
        if (!Object.keys(add).length) throw new Error('already set');
        vault.write(c.path, setNoteFields(text, add));
      } else if (c.kind === 'create') {
        if (vault.read(c.path) !== undefined && c.path !== ONTOLOGY_NOTE) throw new Error('exists now');
        vault.write(c.path, c.content);
      } else if (c.kind === 'index') {
        const text = vault.read(c.path);
        if (!text?.includes(INDEX_START)) throw new Error('markers gone');
        vault.write(c.path, c.content);
      } else {
        vault.move(c.from, c.to);
        if (c.redirect) vault.write(c.from, `---\ntype: redirect\nmoved_to: "${wikiLink(c.to)}"\n---\n\nMoved to ${wikiLink(c.to)}.\n`);
      }
      done.push(describe(c));
    } catch (err) {
      skipped.push(`${describe(c)} — skipped: ${err instanceof Error ? err.message : String(err)}`);
    }
  }
  const date = toLocalIso(now, timeZone).slice(0, 10);
  let log = `${BOT_FOLDER}/Migrations/${date} ontology.md`;
  for (let n = 2; vault.read(log) !== undefined; n++) log = `${BOT_FOLDER}/Migrations/${date} ontology ${n}.md`;
  vault.write(log, `---\ntype: note\ntags: [squire-migration]\n---\n\n# Ontology migration ${date}\n\n${done.map((d) => `- ${d}`).join('\n') || '- nothing to do'}\n${skipped.length ? `\n## Skipped\n\n${skipped.map((s) => `- ${s}`).join('\n')}\n` : ''}`);
  return { done, skipped, log };
}

/** One line for the notes prompt: which fields to write when Squire makes a typed note. */
export const ONTOLOGY_PROMPT = `- Typed notes: when you create a trip, place, person, project or meeting note, start it with frontmatter \`type:\` and that type's fields from ${ONTOLOGY_NOTE} (read it if you don't know them). Put a place in a trip's folder with \`trip: "[[Travel/<Trip>/<Trip>]]"\`. Never change a field the owner set.`;

