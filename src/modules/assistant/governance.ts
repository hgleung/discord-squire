import type { ActivityLog } from './activity.js';
import { FACTORY_FOLDER } from './factoryGuard.js';
export { checkWritePath } from './factoryGuard.js';
import { jobNames, jobPrompt, jobSettings, type JobSettings } from './factory.js';
import { toLocalIso } from './time.js';
import type { Usage } from './llm.js';
import { costUsd, dollars } from './usage.js';

/**
 * What each factory job may do, enforced in code from its job note:
 *
 *   tools          the only tools a job task gets (beyond reporting back); empty = all its kind gets.
 *                  web_search / web_fetch in the list turn on the API's web tools.
 *   write_paths    the only folders its save_note may write; empty = anywhere the notes tools allow.
 *   daily_cap_usd  the most it may spend in a day, from the activity log. A task over it is stopped;
 *                  a new one isn't started; a code job's run is skipped. The brief itself isn't capped.
 *
 * And Factory/Registry.md: one generated table of every job, its limits, its
 * last eval and what it cost in the last 7 days.
 */

export const REGISTRY_NOTE = `${FACTORY_FOLDER}/Registry.md`;
/** Tools a job task always has: the ones it reports back with. */
export const TASK_CORE_TOOLS = ['post_update', 'wait_until', 'finish_task'];
export const WEB_TOOLS = ['web_search', 'web_fetch'];

/** Whether a job task may use this tool. */
export const toolAllowed = (s: JobSettings | undefined, name: string) => !s || !s.tools.length || TASK_CORE_TOOLS.includes(name) || s.tools.includes(name);
/** Whether a job task gets the API's web search and fetch. */
export const webAllowed = (s: JobSettings | undefined) => !s || !s.tools.length || s.tools.some((t) => WEB_TOOLS.includes(t) || t === 'web');

/** Local midnight today, as a Date. */
function startOfDay(now: Date, timeZone: string): Date {
  const local = toLocalIso(now, timeZone);
  return new Date(`${local.slice(0, 10)}T00:00:00${local.slice(19)}`);
}

/** What a job's recorded runs cost between two times. */
export function jobSpend(activity: ActivityLog | undefined, job: string, since: Date, until = new Date()): number {
  if (!activity) return 0;
  return activity.read(since, until).filter((e) => e.job === job).reduce((sum, e) => sum + (e.costUsd ?? 0), 0);
}

/**
 * Why a job may not spend more today, or undefined when it may. `running` is
 * what an unfinished run has used so far (it isn't in the log until it ends).
 */
export function overCap(vault: Vault | undefined, activity: ActivityLog | undefined, job: string, timeZone: string, now = new Date(), running?: Usage): string | undefined {
  const cap = jobSettings(vault, job).dailyCapUsd;
  if (!cap || !activity) return undefined;
  const spent = jobSpend(activity, job, startOfDay(now, timeZone), now) + (running ? costUsd(running) : 0);
  return spent >= cap ? `The ${job} job has spent ${dollars(spent)} today, over its daily cap of ${dollars(cap)} (daily_cap_usd in Factory/Jobs/${job}.md).` : undefined;
}

const cell = (s: string) => s.replace(/\|/g, '/');

/** Factory/Registry.md's text. */
export function registryNote(vault: Vault, activity: ActivityLog | undefined, lastEval: (job: string) => { passed: number; total: number; date: string } | undefined, now = new Date()): string {
  const weekAgo = new Date(now.getTime() - 7 * 86_400_000);
  const rows = jobNames(vault).map((job) => {
    const s = jobSettings(vault, job);
    let prompt = '';
    try {
      prompt = jobPrompt(vault, job).name;
    } catch {
      prompt = 'none in production';
    }
    const e = lastEval(job);
    const rate = e ? `${e.total ? Math.round((e.passed / e.total) * 100) : 0}% (${e.passed}/${e.total}, ${e.date.slice(0, 10)})` : '—';
    const cost = activity ? dollars(jobSpend(activity, job, weekAgo, now)) : '—';
    return `| ${job} | ${s.kind} | ${s.trigger} | ${s.tier}${s.effort ? ` (${s.effort})` : ''} | ${cell(s.tools.join(', ') || 'all its kind gets')} | ${cell(s.writePaths.join(', ') || 'anywhere allowed')} | ${s.shadow ? 'yes' : 'no'} | ${cell(prompt)} | ${rate} | ${s.dailyCapUsd ? dollars(s.dailyCapUsd) : 'none'} | ${cost} |`;
  });
  return `---\ntype: note\ntags: [squire-registry]\n---\n\n# Job registry\n\nGenerated by Squire from the job notes in Factory/Jobs, the eval results and the activity log; edit the job notes, not this. The limits are enforced in code: a job task gets only its tools, saves only under its write paths, and stops at its daily cap.\n\n| Job | Kind | Trigger | Tier | Tools | Write paths | Shadow | Prompt | Last eval | Cap/day | Cost, 7 days |\n|---|---|---|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
}

/** Writes Factory/Registry.md when it changed. Returns whether it wrote. */
export function updateRegistryNote(vault: Vault, activity: ActivityLog | undefined, lastEval: Parameters<typeof registryNote>[2], now = new Date()): boolean {
  return vault.write(REGISTRY_NOTE, registryNote(vault, activity, lastEval, now));
}
